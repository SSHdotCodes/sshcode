// Run with `node packages/shared/scripts/generate-emoji.mjs` from the repository root.
// GitHub's gemoji data is MIT licensed: https://github.com/github/gemoji/blob/master/LICENSE
import * as NodeFSP from "node:fs/promises";

const revision = "fadaeaf1f1a9be82b321316a6c5502e43138b2f6";
const response = await fetch(
  `https://raw.githubusercontent.com/github/gemoji/${revision}/db/emoji.json`,
);
if (!response.ok) throw new Error(`Emoji download failed: ${response.status}`);
const data = await response.json();
const rows = data.map(({ emoji, aliases, tags, description }) => [
  emoji,
  aliases.join(" "),
  [
    ...new Set([
      ...tags,
      ...description
        .toLowerCase()
        .split(/[^a-z0-9]+/)
        .filter(Boolean),
    ]),
  ].join(" "),
]);
await NodeFSP.writeFile(
  new URL("../src/emojiData.ts", import.meta.url),
  `// Generated by scripts/generate-emoji.mjs from github/gemoji@${revision}.\n` +
    "// MIT licensed data, copyright GitHub, Inc. See emojiData.LICENSE.\n" +
    'import type { EmojiEntry } from "./emoji.ts";\n\n' +
    `export const emojiData: ReadonlyArray<EmojiEntry> = ${JSON.stringify(rows)};\n`,
);
const license = await fetch(`https://raw.githubusercontent.com/github/gemoji/${revision}/LICENSE`);
if (!license.ok) throw new Error(`Emoji license download failed: ${license.status}`);
await NodeFSP.writeFile(new URL("../src/emojiData.LICENSE", import.meta.url), await license.text());
console.log(`Generated ${rows.length} emoji.`);
