export const layerBrowserApiCors = Layer.unwrap(
  Effect.gen(function* () {
    const config = yield* ServerConfig.ServerConfig;
    const devOrigin = config.devUrl?.origin;
    const appOrigins = appBrowserOrigins(config);
    // Dev uses credentialed requests from Vite or the Electron custom origin, so both must be
    // explicit. Packaged desktop omits credentials and uses Effect's default wildcard origin.
    //
    // T3CODE_DEV_ALLOWED_ORIGINS covers dev servers reached from a second
    // origin — a tailnet name, a LAN IP, a phone. Browser dev normally proxies
    // through Vite and is same-origin (no preflight at all), so this is a
    // safety net for the desktop renderer and any direct-to-backend caller.
    const corsOptions = {
      allowedMethods: browserApiCorsAllowedMethods,
      allowedHeaders: browserApiCorsAllowedHeaders,
      maxAge: 600,
      ...(devOrigin ? { credentials: true } : {}),
    };
    const cors = HttpMiddleware.cors({
      ...corsOptions,
      ...(devOrigin ? { allowedOrigins: [...appOrigins] } : {}),
    });
    // Outside apps call MCP OAuth from their own processes, and the approval page is
    // the server's own, so no other site may read these answers.
    const mcpOAuthCors = HttpMiddleware.cors({
      ...corsOptions,
      allowedOrigins: (origin) => appOrigins.has(origin),
    });
    return HttpRouter.middleware(
      (app) =>
        Effect.gen(function* () {
          const request = yield* HttpServerRequest.HttpServerRequest;
          // Token-only capture accepts browser posts without the app's credentials, and MCP
          // refuses every browser Origin itself.
          if (
            request.url.startsWith(`${DEBUG_LOG_ROUTE_PREFIX}/`) ||
            request.url.split("?", 1)[0] === MCP_HTTP_PATH
          ) {
            return yield* app;
          }
          return yield* routedPath(request.url).startsWith(MCP_OAUTH_PATH_PREFIX)
            ? mcpOAuthCors(app)
            : cors(app);
        }),
      { global: true },
    );
  }),
);

export function resolveDevRedirectUrl(devUrl: URL, requestUrl: URL): string {
  const redirectUrl = new URL(devUrl.toString());
  redirectUrl.pathname = requestUrl.pathname;
  redirectUrl.search = requestUrl.search;
  redirectUrl.hash = requestUrl.hash;
  return redirectUrl.toString();
}

const authenticateRawRouteWithScope = (
  scope: typeof AuthOrchestrationReadScope | typeof AuthOrchestrationOperateScope,
) =>
  Effect.gen(function* () {
    const request = yield* HttpServerRequest.HttpServerRequest;
    const serverAuth = yield* EnvironmentAuth.EnvironmentAuth;
    const session = yield* serverAuth.authenticateHttpRequest(request).pipe(
      Effect.catchIf(EnvironmentAuth.isServerAuthCredentialError, (error) =>
        failEnvironmentAuthInvalid(
          EnvironmentAuth.serverAuthCredentialReason(error),
          EnvironmentAuth.serverAuthDpopFailureReason(error),
        ),
      ),
      Effect.catchIf(EnvironmentAuth.isServerAuthInternalError, (error) =>
        failEnvironmentInternal("internal_error", error),
      ),
    );
    if (!session.scopes.includes(scope)) {
      return yield* failEnvironmentScopeRequired(scope);
    }
  });

