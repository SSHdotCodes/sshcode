const clientLaunchHarness = (input: {
  readonly runtimeModeCeiling:
    | "read-only"
    | "approval-required"
    | "auto-accept-edits"
    | "auto"
    | "full-access";
  readonly launched: Array<ThreadLaunch.ThreadLaunchInput>;
  readonly workspaceRoot?: string;
  readonly checkWorktreeBase?: ThreadLaunch.ThreadLaunchService["Service"]["checkWorktreeBase"];
  readonly onEnsureScratch?: () => void;
}) => {
  const projectId = ProjectId.make("project:client-target");
  const scratchProjectId = ProjectId.make("project:scratch");
  // "claudeAgent" is the real default instance id for the Claude driver
  // (see `defaultInstanceIdForDriver`), so it resolves as enabled by default
  // under the project-scoped provider instance gate the launch path now runs.
  const modelSelection = {
    instanceId: ProviderInstanceId.make("claudeAgent"),
    model: "claude-opus",
  };
  let scratchCreated = false;
  const layerDependencies = Layer.mergeAll(
    ServerSettings.layerTest({ defaultModelSelection: modelSelection }),
    NodeCrypto.layer,
    Layer.succeed(McpInvocationContext.McpInvocationContext, {
      environmentId: EnvironmentId.make("environment"),
      requestNamespace: "client:session-1",
      thread: undefined,
      client: {
        sessionId: "session-1",
        label: "Claude Code",
        access: input.runtimeModeCeiling,
      },
      issuedAt: 0,
      capabilities: new Set(["orchestration" as const]),
    }),
    Layer.mock(ThreadManagement.ThreadManagementService)({}),
    Layer.mock(ThreadLaunch.ThreadLaunchService)({
      checkWorktreeBase: input.checkWorktreeBase ?? (() => Effect.void),
      launch: (launch) => {
        input.launched.push(launch);
        return Effect.succeed({
          threadId: launch.threadId,
          projection: {
            thread: {
              id: launch.threadId,
              projectId: launch.projectId,
              modelSelection: launch.modelSelection,
            },
            runs: [],
          },
          resumed: false,
        } as unknown as ThreadLaunch.ThreadLaunchResult);
      },
    }),
    Layer.mock(Project.ProjectService)({
      getById: (id) =>
        Effect.succeed(
          id === projectId
            ? Option.some({
                id,
                workspaceRoot: input.workspaceRoot ?? "/projects/client-target",
                defaultModelSelection: modelSelection,
              } as unknown as ProjectRecord)
            : id === scratchProjectId && scratchCreated
              ? Option.some({
                  id,
                  title: "No project",
                  workspaceRoot: "/scratch",
                  defaultModelSelection: null,
                } as unknown as ProjectRecord)
              : Option.none(),
        ),
    }),
    Layer.mock(ManagedProjectFolders.ManagedProjectFolders)({
      namedProjectsRoot: "/projects",
      ensureScratchProject: Effect.sync(() => {
        input.onEnsureScratch?.();
        scratchCreated = true;
        return { projectId: scratchProjectId };
      }),
    }),
    NodeServices.layer,
  ).pipe(
    Layer.provideMerge(GitVcsDriver.layer),
    Layer.provideMerge(VcsProcess.layer),
    Layer.provideMerge(
      ServerConfig.layerTest(process.cwd(), { prefix: "t3-client-launch-" }).pipe(
        Layer.provide(NodeServices.layer),
      ),
    ),
    Layer.provideMerge(NodeServices.layer),
  );
  return { projectId, scratchProjectId, modelSelection, dependencies: layerDependencies };
};

it.effect(
  "a client launches at its ceiling, defaults to scratch without projectId, and rejects unknown ids clearly",
  () =>
    Effect.gen(function* () {
      const launched: Array<ThreadLaunch.ThreadLaunchInput> = [];
      const { projectId, scratchProjectId, modelSelection, dependencies } = clientLaunchHarness({
        runtimeModeCeiling: "auto-accept-edits",
        launched,
      });
      const toolkit = yield* ProjectToolkit.pipe(
        Effect.provide(
          McpToolAccess.HandlersLayer.layer(ProjectHandlers.layer).pipe(
            Layer.provide(dependencies),
          ),
        ),
      );
      const handle = (params: Parameters<typeof toolkit.handle<"t3_thread_launch">>[1]) =>
        toolkit
          .handle("t3_thread_launch", params)
          .pipe(Stream.unwrap, Stream.runCollect, Effect.provide(dependencies));

      const result = yield* handle({ title: "Fix", projectId, message: "Fix the bug" });
      expect(result.at(-1)?.result).toMatchObject({ projectId, modelSelection });
      expect(launched[0]?.runtimeMode).toBe("auto-accept-edits");
      expect(launched[0]?.initialMessage?.senderThreadId).toBeUndefined();

      const escalated = yield* handle({ title: "Fix", projectId, runtimeMode: "full-access" });
      expect(escalated.at(-1)?.result).toMatchObject({ code: "runtime_mode_escalation_denied" });

      const unknown = yield* handle({
        title: "Fix",
        projectId: ProjectId.make("project:does-not-exist"),
      });
      expect(unknown.at(-1)?.result).toMatchObject({
        code: "invalid_request",
        message:
          "Unknown project. Omit projectId to start a chat with no project, or call t3_project_list.",
      });

      const scratchLaunch = yield* handle({ title: "Quick test", message: "Spin up an agent" });
      expect(scratchLaunch.at(-1)?.result).toMatchObject({
        projectId: scratchProjectId,
        modelSelection,
      });
      expect(launched).toHaveLength(2);
      expect(launched[1]?.projectId).toBe(scratchProjectId);
      expect(launched[1]?.runtimeMode).toBe("auto-accept-edits");
      expect(launched[1]?.workspaceStrategy).toEqual({ type: "root" });

      let readOnlyEnsures = 0;
      const readOnlyLaunched: Array<ThreadLaunch.ThreadLaunchInput> = [];
      const readOnly = clientLaunchHarness({
        runtimeModeCeiling: "read-only",
        launched: readOnlyLaunched,
        onEnsureScratch: () => {
          readOnlyEnsures += 1;
        },
      });
      const readOnlyToolkit = yield* ProjectToolkit.pipe(
        Effect.provide(
          McpToolAccess.HandlersLayer.layer(ProjectHandlers.layer).pipe(
            Layer.provide(readOnly.dependencies),
          ),
        ),
      );
      const readOnlyDenied = yield* readOnlyToolkit
        .handle("t3_thread_launch", { title: "Denied" })
        .pipe(Stream.unwrap, Stream.runCollect, Effect.provide(readOnly.dependencies));
      expect(readOnlyDenied.at(-1)?.result).toMatchObject({ code: "capability_denied" });
      expect(readOnlyEnsures).toBe(0);
      expect(readOnlyLaunched).toHaveLength(0);
    }),
);

it.effect("a launch binds only an existing checkout that is one of the project's worktrees", () =>
  Effect.gen(function* () {
    const fileSystem = yield* FileSystem.FileSystem;
    const path = yield* Path.Path;
    const root = yield* fileSystem.makeTempDirectoryScoped({ prefix: "t3-launch-worktree-" });
    const repo = path.join(root, "repo");
    const worktree = path.join(root, "feature");
    const outside = path.join(root, "outside");
    yield* fileSystem.makeDirectory(repo);
    yield* fileSystem.makeDirectory(outside);

    const launched: Array<ThreadLaunch.ThreadLaunchInput> = [];
    const { projectId, dependencies } = clientLaunchHarness({
      runtimeModeCeiling: "auto",
      launched,
      workspaceRoot: repo,
    });
    const git = yield* GitVcsDriver.GitVcsDriver.pipe(Effect.provide(dependencies));
    for (const args of [
      ["init", "-b", "main"],
      ["-c", "user.email=t@t", "-c", "user.name=t", "commit", "--allow-empty", "-m", "init"],
      ["worktree", "add", "-b", "feature", worktree],
    ]) {
      yield* git.execute({ operation: "test.setupRepo", cwd: repo, args });
    }
    const toolkit = yield* ProjectToolkit.pipe(
      Effect.provide(
        McpToolAccess.HandlersLayer.layer(ProjectHandlers.layer).pipe(Layer.provide(dependencies)),
      ),
    );
    const launchInto = (worktreePath: string) =>
      toolkit
        .handle("t3_thread_launch", {
          title: "Fix",
          projectId,
          workspaceStrategy: { type: "existing_worktree", worktreePath },
        })
        .pipe(Stream.unwrap, Stream.runCollect, Effect.provide(dependencies));

    expect((yield* launchInto(worktree)).at(-1)?.result).toMatchObject({ projectId });
    expect((yield* launchInto(repo)).at(-1)?.result).toMatchObject({ projectId });
    for (const elsewhere of [outside, path.join(worktree, "..", "outside"), "/"]) {
      expect((yield* launchInto(elsewhere)).at(-1)?.result).toMatchObject({
        code: "invalid_request",
      });
    }
    expect(launched.map((launch) => launch.workspaceStrategy)).toEqual([
      { type: "existing_worktree", worktreePath: worktree },
      { type: "existing_worktree", worktreePath: repo },
    ]);

    // A removed worktree stays listed as prunable until `git worktree prune`;
    // whatever directory is later made at its path is not one of the project's.
    yield* fileSystem.remove(worktree, { recursive: true });
    yield* fileSystem.makeDirectory(worktree);
    expect((yield* launchInto(worktree)).at(-1)?.result).toMatchObject({
      code: "invalid_request",
    });
  }).pipe(Effect.scoped, Effect.provide(NodeServices.layer)),
);

it.effect("a launch into a new worktree creates nothing when its base ref has no commit", () =>
  Effect.gen(function* () {
    const launched: Array<ThreadLaunch.ThreadLaunchInput> = [];
    const { projectId, dependencies } = clientLaunchHarness({
      runtimeModeCeiling: "auto",
      launched,
      checkWorktreeBase: ({ projectId, workspaceStrategy }) =>
        workspaceStrategy.type === "worktree" && workspaceStrategy.baseRef === "t3/renamed"
          ? Effect.fail(
              new ThreadLaunch.ThreadLaunchBaseRefError({
                projectId,
                projectTitle: "Client target",
                workspaceRoot: "/projects/client-target",
                baseRef: workspaceStrategy.baseRef,
              }),
            )
          : Effect.void,
    });
    const toolkit = yield* ProjectToolkit.pipe(
      Effect.provide(
        McpToolAccess.HandlersLayer.layer(ProjectHandlers.layer).pipe(Layer.provide(dependencies)),
      ),
    );
    const launchFrom = (baseRef: string) =>
      toolkit
        .handle("t3_thread_launch", {
          title: "Fix",
          projectId,
          workspaceStrategy: { type: "worktree", baseRef, startFromOrigin: false },
        })
        .pipe(Stream.unwrap, Stream.runCollect, Effect.provide(dependencies));

    const refused = (yield* launchFrom("t3/renamed")).at(-1)?.result;
    expect(refused).toMatchObject({ code: "invalid_request" });
    expect((refused as { message: string }).message).toContain(
      'Base ref "t3/renamed" does not resolve to a commit in project "Client target" (/projects/client-target). No thread was created.',
    );
    expect(launched).toHaveLength(0);

    expect((yield* launchFrom("main")).at(-1)?.result).toMatchObject({ projectId });
    expect(launched).toHaveLength(1);
  }),
);

